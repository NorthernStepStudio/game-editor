export function renderGuide(host, sectionId) {
  clear(host,
    h('div', { class: 'guide' },
      h('section', { class: 'card' },
        h('h2', {}, 'How Matterhorn works'),
        h('p', { class: 'muted' }, 'Every place, every button, and the common tasks. Jump to a section:'),
        h('nav', { class: 'guide-toc', 'aria-label': 'Guide sections' },
          SECTIONS.map((s) => h('a', { class: 'btn small', href: `#settings/guide/${s.id}` }, s.title)))),
      SECTIONS.map((s) => h('section', { class: 'card', id: `guide-${s.id}`, 'aria-labelledby': `guide-${s.id}-title` },
        h('h2', { id: `guide-${s.id}-title` }, s.title),
        s.body()))));
  if (sectionId) document.querySelector(`#guide-${sectionId}`)?.scrollIntoView?.({ block: 'start' });
}

export const GUIDE_SECTION_IDS = SECTIONS.map((s) => s.id);
